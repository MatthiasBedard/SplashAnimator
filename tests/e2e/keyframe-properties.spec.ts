import { expect, test } from '@playwright/test';
import { newProject, type Project } from '../../packages/document/src';

test('Keyframe properties target the selected key and reuse frame history and script authoring', async ({ page }) => {
  const project = newProject();
  const layer = project.layers[0];
  layer.name = 'Artwork';
  layer.drawingMode = 'object';
  project.duration = 10;
  layer.keys.push({ frame: 3, shapes: [{
    id: 'art', kind: 'rectangle', x: 20, y: 20, width: 50, height: 30, rotation: 0,
    fill: '#ff0000', stroke: '#000000', strokeWidth: 0, points: [],
  }] });
  project.frameComments = [{ frame: 3, text: 'Start the movement' }];
  project.frameLabels = [{ frame: 0, name: 'Opening' }];
  await page.addInitScript(project => {
    localStorage.setItem('splash-recovery-v1', JSON.stringify({ project, folder: null, manifest: null }));
  }, project);
  await page.goto('/');
  const splash = page.getByRole('button', { name: 'Open editor', exact: true });
  const recover = page.getByRole('button', { name: 'Recover changes', exact: true });
  await expect(splash.or(recover).first()).toBeVisible();
  if (await splash.isVisible()) await splash.click();
  await recover.click();
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('splash-recovery-v1')!).project as Project);
  const timeline = page.getByLabel('Timeline frames', { exact: true });
  const panel = page.locator('[data-keyframe-properties]');
  const cell = (at: number) => timeline.click({ position: { x: 18 * at + 8, y: 40 } });
  const tween = panel.locator('dt:has-text("Tween type") + dd');

  await cell(0);
  await expect(panel).toContainText('1 · Artwork');
  await expect(panel).toContainText('Blank');
  await expect(panel).toContainText('Opening');
  await timeline.press('ArrowRight');
  await expect(panel).toHaveCount(0);
  await cell(3);
  await expect(panel).toContainText('4 · Artwork');
  await expect(panel).toContainText('Start the movement');
  await expect(tween).toHaveText('None');
  const editLabel = panel.getByRole('button', { name: 'Edit label…', exact: true });
  await editLabel.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'Edit frame label', exact: true });
  await dialog.getByLabel('Frame label name').fill('Movement');
  await dialog.getByRole('button', { name: 'Save frame label', exact: true }).click();
  await expect(panel).toContainText('Movement');
  await expect(editLabel).toBeFocused();
  const labeled = await read();
  expect(labeled.frameLabels).toEqual([...project.frameLabels, { frame: 3, name: 'Movement' }]);
  await timeline.press('Control+z');
  expect(await read()).toEqual(project);
  await timeline.press('Control+Shift+z');
  expect(await read()).toEqual(labeled);
  await cell(3);

  await panel.getByRole('button', { name: 'Create motion tween', exact: true }).click();
  await expect(tween).toHaveText('Motion tween');
  const editEase = panel.getByRole('button', { name: 'Edit easing…', exact: true });
  const motion = await read();
  expect(motion.layers[0].keys.at(-1)?.openMotionTween).toBeDefined();
  await editEase.press('Enter');
  const timing = page.getByRole('dialog', { name: 'Edit motion tween easing', exact: true });
  const easing = timing.getByLabel('Tween easing', { exact: true });
  await expect(easing).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  const close = timing.getByRole('button', { name: 'Close dialog', exact: true });
  await expect(close).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(timing.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(timing).toHaveCount(0);
  await expect(editEase).toBeFocused();
  expect(await read()).toEqual(motion);
  await editEase.press('Enter');
  await easing.press('ArrowDown');
  await expect(easing).toHaveValue('in');
  await timing.getByRole('button', { name: 'Apply easing', exact: true }).press('Enter');
  await expect(timing).toHaveCount(0);
  await expect(editEase).toBeFocused();
  expect((await read()).layers[0].keys.at(-1)?.openMotionTween?.ease).toBe('in');
  await page.keyboard.press('Control+z');
  expect(await read()).toEqual(motion);
  await page.keyboard.press('Control+Shift+z');
  expect((await read()).layers[0].keys.at(-1)?.openMotionTween?.ease).toBe('in');
  await panel.getByRole('button', { name: 'Remove motion tween', exact: true }).click();
  await expect(tween).toHaveText('None');
  expect((await read()).layers[0].keys.at(-1)?.openMotionTween).toBeUndefined();
  await panel.getByRole('button', { name: 'Open frame script', exact: true }).click();
  const script = page.getByRole('dialog', { name: 'Edit frame source', exact: true });
  await expect(script).toContainText('frame 4');
  expect((await read()).frameScripts).toEqual([{ frame: 3, source: '// Code goes here.\n' }]);
  await expect(panel).toContainText('Attached');
  await script.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await cell(0);
  await timeline.press('Shift+ArrowRight');
  await expect(panel).toHaveCount(0);
});
